# Mapping catégorie -> tableau de points
CATEGORY_POINTS = {
    "P25": POINTS_P25,
    "P100": POINTS_P100,
    "P250": POINTS_P250,
    "P500": POINTS_P500,
    "P1000": POINTS_P1000,
    "P2000": POINTS_P2000,
}


def get_teams_column_index(num_teams: int) -> int:
    """
    Retourne l'index de colonne basé sur le nombre d'équipes
    0 = 4-8 paires
    1 = 9-12 paires
    2 = 13-16 paires
    3 = 17-20 paires
    4 = 21-24 paires
    5 = 25-28 paires
    6 = 29-32+ paires
    """
    if num_teams <= 8:
        return 0
    elif num_teams <= 12:
        return 1
    elif num_teams <= 16:
        return 2
    elif num_teams <= 20:
        return 3
    elif num_teams <= 24:
        return 4
    elif num_teams <= 28:
        return 5
    else:
        return 6


def get_points(category: str, rank: int, num_teams: int) -> int:
    """
    Calcule les points pour un rang donné dans une catégorie
    
    Args:
        category: Catégorie du tournoi (P25, P100, P250, P500, P1000, P2000)
        rank: Rang final de l'équipe (1 = vainqueur, 2 = finaliste, etc.)
        num_teams: Nombre total d'équipes dans le tournoi
    
    Returns:
        Nombre de points attribués
    """
    points_table = CATEGORY_POINTS.get(category.upper())
    if not points_table:
        return 0
    
    column_index = get_teams_column_index(num_teams)
    
    # Gérer les rangs au-delà de 32
    if rank > 32:
        rank = 32
    
    points_row = points_table.get(rank)
    if not points_row:
        return 0
    
    return points_row[column_index]


def calculate_tournament_rankings(category: str, num_teams: int, final_rankings: List[Dict]) -> List[Dict]:
    """
    Calcule les points pour toutes les équipes d'un tournoi
    
    Args:
        category: Catégorie du tournoi
        num_teams: Nombre total d'équipes
        final_rankings: Liste des équipes avec leur rang final
                       [{"team_id": "xxx", "rank": 1, "team_name": "..."}, ...]
    
    Returns:
        Liste avec les points calculés
        [{"team_id": "xxx", "rank": 1, "team_name": "...", "points": 25}, ...]
    """
    results = []
    for team_data in final_rankings:
        rank = team_data.get("rank", 32)
        points = get_points(category, rank, num_teams)
        results.append({
            **team_data,
            "points": points
        })
    
    return results


def get_available_categories() -> List[str]:
    """Retourne la liste des catégories disponibles"""
    return list(CATEGORY_POINTS.keys())